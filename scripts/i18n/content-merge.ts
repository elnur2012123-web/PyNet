/**
 * Merges scripts/i18n/content-work/<group>.json ({ uz: [...], ru: [...] }, same order as
 * content-todo/<group>.json) into src/i18n/content/<group>.ts and registers it in index.ts.
 * Fails if any `code span` from the English text is missing or changed in a translation.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
const groups = process.argv.slice(2);
const spans = (s: string) => (s.match(/```[\s\S]*?```|`[^`\n]+`/g) ?? []).sort();
let bad = 0;
for (const g of groups) {
  const en: string[] = JSON.parse(readFileSync(`scripts/i18n/content-todo/${g}.json`, "utf8"));
  const work = JSON.parse(readFileSync(`scripts/i18n/content-work/${g}.json`, "utf8")) as { uz: string[]; ru: string[] };
  if (work.uz.length !== en.length || work.ru.length !== en.length) { console.log(`✗ ${g}: lengths en=${en.length} uz=${work.uz.length} ru=${work.ru.length}`); bad++; continue; }
  const triples: [string, string, string][] = [];
  en.forEach((e, i) => {
    for (const [lang, t] of [["uz", work.uz[i]], ["ru", work.ru[i]]] as const) {
      const need = spans(e);
      const got = spans(t);
      const missing = need.filter((s) => !got.includes(s));
      if (missing.length) { console.log(`✗ ${g}[${i}] ${lang}: code changed/missing ${JSON.stringify(missing)}\n   en: ${e.slice(0, 120)}\n   ${lang}: ${t.slice(0, 120)}`); bad++; }
    }
    triples.push([e, work.uz[i], work.ru[i]]);
  });
  const name = g.toUpperCase().replace(/[^A-Z0-9]/g, "_");
  const path = `src/i18n/content/${g}.ts`;
  const prev: [string, string, string][] = existsSync(path) ? JSON.parse(readFileSync(path, "utf8").replace(/^[\s\S]*?= /, "").replace(/;\s*$/, "")) : [];
  const merged = new Map(prev.map((t) => [t[0], t] as const));
  for (const t of triples) merged.set(t[0], t);
  writeFileSync(path, `// [English, Oʻzbekcha (lotin), Русский] — generated by scripts/i18n/content-merge.ts\nexport const ${name}: [string, string, string][] = ${JSON.stringify([...merged.values()], null, 1)};\n`);
  console.log(`✓ ${g}: ${triples.length} strings`);
}
// index.ts imports every group file
const files = readdirSync("src/i18n/content").filter((f) => f !== "index.ts" && f.endsWith(".ts")).map((f) => f.replace(/\.ts$/, "")).sort();
writeFileSync("src/i18n/content/index.ts",
  `// Human translations of learning content: [English, Oʻzbekcha (lotin), Русский].\n// Code inside \`backticks\` is never transliterated or changed.\n` +
  files.map((f) => `import { ${f.toUpperCase().replace(/[^A-Z0-9]/g, "_")} } from "./${f}";`).join("\n") +
  `\nexport const CONTENT: [string, string, string][] = [${files.map((f) => `...${f.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`).join(", ")}];\n`);
if (bad) { console.log(`${bad} problems`); process.exit(1); }
