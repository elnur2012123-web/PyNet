/**
 * Builds supabase/migrations/0010_problems_seed.sql from scripts/problems/data.ts.
 * Every reference solution is run in real Python (Pyodide) on every test; examples
 * must match their written outputs exactly, otherwise the build fails.
 *   npm run build:problems
 */
import { readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { loadPyodide } from "pyodide";
import { PROBLEMS, SEED_CONTESTS } from "./problems/data";

const norm = (s: string) => s.replace(/\r\n/g, "\n").split("\n").map((l) => l.replace(/\s+$/, "")).join("\n").replace(/\n+$/, "");
const sql = (s: string) => `'${s.replace(/'/g, "''")}'`;

async function main() {
  const py = await loadPyodide();
  let buf: string[] = [];
  py.setStdout({ write: (b: Uint8Array) => { buf.push(new TextDecoder().decode(b)); return b.length; } });
  py.runPython(`
import sys, io, builtins
def _pn_judge_setup(data):
    sys.stdin = io.TextIOWrapper(io.BytesIO(data.encode()), encoding="utf-8")
    def _input(prompt=""):
        line = sys.stdin.readline()
        if not line:
            raise EOFError("EOF when reading a line")
        return line.rstrip("\\n")
    builtins.input = _input
`);
  const setup = py.globals.get("_pn_judge_setup");
  const run = (code: string, input: string) => {
    buf = [];
    setup(input);
    const ns = py.globals.get("dict")();
    ns.set("__name__", "__main__");
    const t = performance.now();
    try { py.runPython(code, { globals: ns }); } finally { ns.destroy(); }
    py.runPython("import sys; sys.stdout.flush()");
    return { out: norm(buf.join("")), ms: performance.now() - t };
  };

  const ids = new Set<number>();
  const header = (what: string) => `-- GENERATED by scripts/build-problems.ts — do not edit by hand.\n-- ${what}\n\n`;
  // One statement per row, so files can be split anywhere between statements.
  const pub: string[] = [];
  const pool: string[] = [];
  let out = "";
  let fails = 0, tests = 0;
  for (const p of PROBLEMS) {
    if (ids.has(p.id)) throw new Error(`duplicate id ${p.id}`);
    ids.add(p.id);
    const all: { input: string; expected: string }[] = [];
    for (const [i, ex] of p.examples.entries()) {
      const r = run(p.solution, ex.input);
      if (r.out !== norm(ex.output)) { fails++; console.log(`✗ ${p.id} example ${i + 1}: expected ${JSON.stringify(norm(ex.output))} got ${JSON.stringify(r.out)}`); }
      all.push({ input: ex.input, expected: r.out });
    }
    let slowest = 0;
    for (const input of p.tests) {
      const r = run(p.solution, input);
      slowest = Math.max(slowest, r.ms);
      all.push({ input, expected: r.out });
    }
    tests += all.length;
    console.log(`✓ ${p.id} ${p.title.padEnd(22)} ${all.length} tests, slowest ${slowest.toFixed(0)} ms`);
    const stmts: string[] = [];
    stmts.push(`insert into public.problems (id, title, statement, input_spec, output_spec, notes, examples, tags, rating, time_limit_ms, visibility) values (${p.id}, ${sql(p.title)}, ${sql(p.statement)}, ${sql(p.input)}, ${sql(p.output)}, ${sql(p.notes ?? "")}, ${sql(JSON.stringify(p.examples.map((e) => ({ input: e.input, output: norm(e.output) }))))}::jsonb, array[${p.tags.map(sql).join(",")}]::text[], ${p.rating}, ${p.timeLimitMs ?? 2000}, ${sql(p.visibility)}) on conflict (id) do nothing;\n`);
    for (const [i, t] of all.entries()) stmts.push(`insert into public.problem_tests (problem_id, idx, input, expected) values (${p.id}, ${i + 1}, ${sql(t.input)}, ${sql(t.expected)}) on conflict do nothing;\n`);
    (p.visibility === "public" ? pub : pool).push(...stmts);
  }
  out = "";
  // Rounds start on the next Saturday at 14:00 UTC after the migration runs, one week apart.
  out += `do $$\ndeclare\n  v_start timestamptz := date_trunc('week', now()) + interval '5 days 14 hours';\n  v_id int;\nbegin\n  if exists (select 1 from public.contests) then return; end if;\n  if v_start < now() + interval '1 day' then v_start := v_start + interval '7 days'; end if;\n`;
  for (const c of SEED_CONTESTS) {
    out += `  insert into public.contests (title, description, starts_at, duration_minutes, rated) values (${sql(c.title)}, ${sql(c.description)}, v_start + interval '${c.dayOffset} days', ${c.durationMinutes}, true) returning id into v_id;\n`;
    out += `  insert into public.contest_problems (contest_id, letter, problem_id) values ${c.problems.map((id, i) => `(v_id, '${"ABCDEFGHIJ"[i]}', ${id})`).join(", ")};\n`;
  }
  out += `end $$;\n`;
  if (fails) { console.log(`\n${fails} failures`); process.exit(1); }
  pool.push(out);
  // The Supabase SQL Editor rejects big queries, so write parts of at most ~250 KB.
  for (const f of readdirSync("supabase/migrations")) if (/^001[01]_/.test(f)) unlinkSync(`supabase/migrations/${f}`);
  const LIMIT = 250 * 1024;
  const write = (prefix: string, name: string, what: string, stmts: string[]) => {
    const parts: string[][] = [[]];
    let size = 0;
    for (const st of stmts) {
      if (size + st.length > LIMIT && parts[parts.length - 1].length) { parts.push([]); size = 0; }
      parts[parts.length - 1].push(st);
      size += st.length;
    }
    parts.forEach((ps, i) => {
      const file = `supabase/migrations/${prefix}_${String(i + 1).padStart(2, "0")}_${name}.sql`;
      const body = header(`${what} — part ${i + 1} of ${parts.length}. Run the parts in order.`) + ps.join("");
      writeFileSync(file, body);
      console.log(`  ${file} (${(body.length / 1024).toFixed(0)} KB)`);
    });
  };
  console.log(`\nWrote ${PROBLEMS.length} problems, ${tests} tests:`);
  write("0010", "problemset_seed", "Problemset (public problems) + their hidden tests", pub);
  write("0011", "contests_seed", "Contest problems (hidden until their round starts) + the first two rounds", pool);
}
main();
