-- =====================================================================
-- 0017: Suggestion bot. Learners (and teachers) send ideas, bug reports and
-- content/translation notes; staff with "read_suggestions" answer them.
-- =====================================================================

-- new permission
create or replace function public.all_permissions() returns text[] language sql immutable as $$
  select array['ban_users','view_logs','view_code','host_contests','create_problems','review_cheating','manage_roles','read_suggestions'];
$$;
update public.roles set permissions = permissions || array['read_suggestions']
 where id in ('co_founder', 'admin') and not ('read_suggestions' = any(permissions));
update public.roles set permissions = public.all_permissions() where id = 'founder';

create table if not exists public.suggestions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('idea','bug','lesson','translation','other')),
  message text not null check (char_length(message) between 5 and 2000),
  page text check (char_length(page) <= 200),
  language text check (char_length(language) <= 10),
  status text not null default 'new' check (status in ('new','planned','done','declined')),
  staff_reply text check (char_length(staff_reply) <= 1000),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists suggestions_status_idx on public.suggestions (status, created_at desc);
create index if not exists suggestions_user_idx on public.suggestions (user_id, created_at desc);

alter table public.suggestions enable row level security;
revoke all on public.suggestions from anon, authenticated;
-- learners can read their own suggestions (to see the team's reply); writes go through the server
grant select on public.suggestions to authenticated;
drop policy if exists suggestions_read_own on public.suggestions;
create policy suggestions_read_own on public.suggestions for select to authenticated using (user_id = auth.uid());
