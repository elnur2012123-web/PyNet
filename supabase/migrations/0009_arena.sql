create or replace function public.get_problemset()
returns table (id integer, title text, tags text[], rating integer, solved bigint, my_status text)
language sql stable security definer set search_path = public as $$
  select p.id, p.title, p.tags, p.rating,
    (select count(distinct s.user_id) from public.submissions s where s.problem_id = p.id and s.verdict = 'OK'),
    case
      when auth.uid() is null then null
      when exists (select 1 from public.submissions s where s.problem_id = p.id and s.user_id = auth.uid() and s.verdict = 'OK') then 'OK'
      when exists (select 1 from public.submissions s where s.problem_id = p.id and s.user_id = auth.uid()) then 'TRIED'
    end
  from public.problems p
  where public.problem_listed(p.id, p.visibility)
  order by p.id;
$$;
grant execute on function public.get_problemset() to anon, authenticated;

