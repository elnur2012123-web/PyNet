-- Leaderboard rows carry the rating so names can be coloured by rank.
drop function if exists public.get_leaderboard(text, int);
create or replace function public.get_leaderboard(p_period text default 'global', p_limit int default 50)
returns table (
  rank bigint, user_id uuid, username text, display_name text, avatar_url text,
  country text, xp bigint, level integer, lessons integer, exercises integer,
  streak integer, plan text, league text, special_title text, badge text, rating integer
) language sql stable security definer set search_path = public as $$
  with weekly as (
    select da.user_id, sum(da.xp_earned)::int as xp from public.daily_activity da
    where da.activity_date >= public.week_start() group by da.user_id
  ), monthly as (
    select da.user_id, sum(da.xp_earned)::int as xp from public.daily_activity da
    where da.activity_date >= public.month_start() group by da.user_id
  ), friends as (
    select case when f.requester_id = auth.uid() then f.receiver_id else f.requester_id end as uid
    from public.friendships f
    where f.status = 'accepted' and auth.uid() in (f.requester_id, f.receiver_id)
    union select auth.uid()
  ), base as (
    select p.id, p.username::text, p.display_name, p.avatar_url, p.country,
      (case p_period when 'weekly' then coalesce(w.xp,0) when 'monthly' then coalesce(m.xp,0) else up.total_xp end)::bigint as xp,
      up.current_level, up.completed_lessons, up.completed_exercises, (case when up.last_activity_date >= (now() at time zone 'utc')::date - 1 then up.current_streak else 0 end) as current_streak,
      coalesce(s.plan,'FREE') as plan, public.league_for_weekly_xp(coalesce(w.xp,0)) as league,
      p.special_title, p.hidden_from_weekly, public.badge_for(p.id) as badge, p.rating
    from public.profiles p
    join public.user_progress up on up.user_id = p.id
    left join weekly w on w.user_id = p.id
    left join monthly m on m.user_id = p.id
    left join public.subscriptions s on s.user_id = p.id and s.status in ('active','on_trial','cancelled','past_due')
    where ((p.is_public and p.show_stats) or p.id = auth.uid())
      and not public.is_banned(p.id)
  )
  select rank() over (order by b.xp desc, b.username) as rank, b.id, b.username, b.display_name,
         b.avatar_url, b.country, b.xp, b.current_level, b.completed_lessons,
         b.completed_exercises, b.current_streak, b.plan, b.league, b.special_title, b.badge, b.rating
  from base b
  where (p_period <> 'friends' or b.id in (select uid from friends))
    and not (p_period in ('weekly', 'monthly') and b.hidden_from_weekly)
    and (p_period in ('global','friends') or b.xp > 0 or b.id = auth.uid())
  order by b.xp desc, b.username
  limit least(greatest(p_limit, 1), 200);
$$;
grant execute on function public.get_leaderboard(text, int) to anon, authenticated;

-- Status page: latest judged submissions (optionally for one user / problem / round).
create or replace function public.get_status(p_username text default null, p_problem integer default null,
                                             p_contest integer default null, p_limit integer default 100)
returns table (id bigint, created_at timestamptz, username text, rating integer, problem_id integer, problem_title text,
               contest_id integer, letter text, verdict text, failed_test integer, time_ms integer)
language sql stable security definer set search_path = public as $$
  select s.id, s.created_at, p.username::text, p.rating, s.problem_id, pr.title, s.contest_id, cp.letter,
         s.verdict, s.failed_test, s.time_ms
  from public.submissions s
  join public.profiles p on p.id = s.user_id
  join public.problems pr on pr.id = s.problem_id
  left join public.contest_problems cp on cp.contest_id = s.contest_id and cp.problem_id = s.problem_id
  where public.problem_readable(pr.id, pr.visibility)
    and (p_username is null or p.username = p_username::citext)
    and (p_problem is null or s.problem_id = p_problem)
    and (p_contest is null or s.contest_id = p_contest)
    and (p.is_public or p.id = auth.uid() or public.is_staff(auth.uid()))
    and not public.is_banned(p.id)
  order by s.id desc
  limit least(greatest(p_limit, 1), 200);
$$;
grant execute on function public.get_status(text, integer, integer, integer) to anon, authenticated;

-- Problems for a round (letters, titles) once it has started; solved counts come from the standings.
create or replace function public.get_contest_problems(p_contest integer)
returns table (letter text, problem_id integer, title text, rating integer, tags text[], time_limit_ms integer)
language sql stable security definer set search_path = public as $$
  select cp.letter, pr.id, pr.title, pr.rating, pr.tags, pr.time_limit_ms
  from public.contest_problems cp join public.problems pr on pr.id = cp.problem_id
  where cp.contest_id = p_contest and (public.contest_started(p_contest) or public.is_staff(auth.uid()))
  order by cp.letter;
$$;
grant execute on function public.get_contest_problems(integer) to anon, authenticated;
