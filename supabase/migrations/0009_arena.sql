-- ICPC-style standings: solved desc, penalty asc (minutes to first OK + 20 per earlier rejected try).
create or replace function public.get_contest_standings(p_contest integer)
returns table (rank bigint, user_id uuid, username text, rating integer, country text,
               solved integer, penalty integer, cells jsonb)
language sql stable security definer set search_path = public as $$
  with c as (
    select id, starts_at, starts_at + make_interval(mins => duration_minutes) as ends_at
    from public.contests where id = p_contest and starts_at <= now()
  ), subs as (
    select s.user_id, cp.letter, s.verdict, s.created_at
    from public.submissions s
    join c on s.contest_id = c.id and s.created_at < c.ends_at
    join public.contest_problems cp on cp.contest_id = c.id and cp.problem_id = s.problem_id
    where s.verdict <> 'CE' and not public.is_banned(s.user_id)
  ), first_ok as (
    select user_id, letter, min(created_at) as ok_at from subs where verdict = 'OK' group by 1, 2
  ), per as (
    select s.user_id, s.letter,
      fo.ok_at is not null as ok,
      count(*) filter (where s.verdict <> 'OK' and (fo.ok_at is null or s.created_at < fo.ok_at))::int as wrong,
      case when fo.ok_at is not null then floor(extract(epoch from fo.ok_at - (select starts_at from c)) / 60)::int end as minute
    from subs s left join first_ok fo on fo.user_id = s.user_id and fo.letter = s.letter
    group by s.user_id, s.letter, fo.ok_at
  ), agg as (
    select user_id,
      count(*) filter (where ok)::int as solved,
      coalesce(sum(minute + 20 * wrong) filter (where ok), 0)::int as penalty,
      jsonb_object_agg(letter, jsonb_build_object('ok', ok, 'wrong', wrong, 'minute', minute)) as cells
    from per group by user_id
  )
  select rank() over (order by a.solved desc, a.penalty asc), a.user_id, p.username::text, p.rating, p.country,
         a.solved, a.penalty, a.cells
  from agg a join public.profiles p on p.id = a.user_id
  order by 1, p.username;
$$;
grant execute on function public.get_contest_standings(integer) to anon, authenticated;

-- Submission code: owner, staff, or someone who has solved that problem themselves
-- (never while the submission's contest is still running).
create or replace function public.get_submission(p_id bigint)
returns table (id bigint, user_id uuid, username text, rating integer, problem_id integer, problem_title text, contest_id integer,
               verdict text, failed_test integer, tests_total integer, time_ms integer, created_at timestamptz,
               code text, can_view_code boolean)
language sql stable security definer set search_path = public as $$
  select s.id, s.user_id, p.username::text, p.rating, s.problem_id, pr.title, s.contest_id, s.verdict, s.failed_test,
    s.tests_total, s.time_ms, s.created_at,
    case when v.ok then s.code end, v.ok
  from public.submissions s
  join public.profiles p on p.id = s.user_id
  join public.problems pr on pr.id = s.problem_id
  cross join lateral (select (
      s.user_id = auth.uid() or public.is_staff(auth.uid())
      or (exists (select 1 from public.submissions m where m.user_id = auth.uid() and m.problem_id = s.problem_id and m.verdict = 'OK')
          and not exists (select 1 from public.contests c where c.id = s.contest_id
                          and c.starts_at + make_interval(mins => c.duration_minutes) > now()))
    ) as ok) v
  where s.id = p_id and public.problem_readable(pr.id, pr.visibility);
$$;
grant execute on function public.get_submission(bigint) to anon, authenticated;

