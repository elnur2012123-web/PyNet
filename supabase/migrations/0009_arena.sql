-- =====================================================================
-- 0009: Arena — problemset, judged submissions, contests, rating.
--
-- * problems        statements (readable when public, or once their contest starts)
-- * problem_tests   hidden test data — NEVER readable from the browser
-- * submissions     every judged attempt; verdicts public, code private
-- * contests        timed rounds with ICPC-style standings
-- * rating_changes  per-contest rating history (Elo-style, applied by the server)
-- =====================================================================

alter table public.profiles add column if not exists rating integer;
alter table public.profiles add column if not exists max_rating integer;

-- ---------------------------------------------------------------- problems
create table if not exists public.problems (
  id integer generated by default as identity (start with 2001) primary key,
  title text not null check (char_length(title) between 3 and 80),
  statement text not null check (char_length(statement) <= 8000),
  input_spec text not null default '' check (char_length(input_spec) <= 3000),
  output_spec text not null default '' check (char_length(output_spec) <= 3000),
  notes text not null default '' check (char_length(notes) <= 3000),
  examples jsonb not null default '[]'::jsonb,           -- [{input, output}]
  tags text[] not null default '{}',
  rating integer not null check (rating between 800 and 3500 and rating % 100 = 0),
  time_limit_ms integer not null default 2000 check (time_limit_ms between 500 and 10000),
  visibility text not null default 'hidden' check (visibility in ('public','hidden')),
  author_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.problem_tests (
  problem_id integer not null references public.problems(id) on delete cascade,
  idx integer not null check (idx between 1 and 100),
  input text not null check (char_length(input) <= 200000),
  expected text not null check (char_length(expected) <= 200000),
  primary key (problem_id, idx)
);

-- ---------------------------------------------------------------- contests
create table if not exists public.contests (
  id integer generated by default as identity primary key,
  title text not null check (char_length(title) between 3 and 100),
  description text not null default '' check (char_length(description) <= 4000),
  starts_at timestamptz not null,
  duration_minutes integer not null check (duration_minutes between 10 and 10080),
  rated boolean not null default true,
  rating_applied boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists contests_starts_idx on public.contests (starts_at);

create table if not exists public.contest_problems (
  contest_id integer not null references public.contests(id) on delete cascade,
  letter text not null check (letter ~ '^[A-J]$'),
  problem_id integer not null references public.problems(id) on delete restrict,
  primary key (contest_id, letter),
  unique (contest_id, problem_id)
);

create table if not exists public.contest_registrations (
  contest_id integer not null references public.contests(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  registered_at timestamptz not null default now(),
  primary key (contest_id, user_id)
);

-- ---------------------------------------------------------------- submissions
create table if not exists public.submissions (
  id bigint generated by default as identity (start with 100001) primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  problem_id integer not null references public.problems(id) on delete cascade,
  contest_id integer references public.contests(id) on delete set null,  -- set only for in-contest attempts
  code text not null check (char_length(code) <= 65536),
  verdict text not null check (verdict in ('OK','WA','RE','TLE','CE')),
  failed_test integer,
  tests_total integer not null,
  time_ms integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists submissions_user_idx on public.submissions (user_id, created_at desc);
create index if not exists submissions_problem_idx on public.submissions (problem_id, verdict);
create index if not exists submissions_contest_idx on public.submissions (contest_id, created_at);
create index if not exists submissions_recent_idx on public.submissions (created_at desc);

create table if not exists public.rating_changes (
  contest_id integer not null references public.contests(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rank integer not null,
  old_rating integer not null,
  new_rating integer not null,
  created_at timestamptz not null default now(),
  primary key (contest_id, user_id)
);

-- ---------------------------------------------------------------- helpers
create or replace function public.contest_started(p_contest integer) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select starts_at <= now() from public.contests where id = p_contest), false);
$$;

-- A hidden problem becomes readable as soon as a contest that uses it starts.
create or replace function public.problem_readable(p_problem integer, p_visibility text) returns boolean
language sql stable security definer set search_path = public as $$
  select p_visibility = 'public'
      or public.is_staff(auth.uid())
      or exists (select 1 from public.contest_problems cp join public.contests c on c.id = cp.contest_id
                 where cp.problem_id = p_problem and c.starts_at <= now());
$$;

-- Listed in the problemset: public, or its contest is over.
create or replace function public.problem_listed(p_problem integer, p_visibility text) returns boolean
language sql stable security definer set search_path = public as $$
  select p_visibility = 'public'
      or exists (select 1 from public.contest_problems cp join public.contests c on c.id = cp.contest_id
                 where cp.problem_id = p_problem
                   and c.starts_at + make_interval(mins => c.duration_minutes) <= now());
$$;

