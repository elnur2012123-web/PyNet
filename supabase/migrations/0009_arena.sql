-- ---------------------------------------------------------------- privileged (service_role)
-- Stores ratings computed by the server, exactly once per contest.
create or replace function public.apply_contest_ratings(p_contest integer, p_changes jsonb)
returns integer language plpgsql security definer set search_path = public as $$
declare
  v_n int := 0;
  r record;
begin
  update public.contests set rating_applied = true
   where id = p_contest and rated and not rating_applied
     and starts_at + make_interval(mins => duration_minutes) <= now();
  if not found then return 0; end if;
  for r in select * from jsonb_to_recordset(p_changes) as x(user_id uuid, rank int, old_rating int, new_rating int) loop
    insert into public.rating_changes (contest_id, user_id, rank, old_rating, new_rating)
    values (p_contest, r.user_id, r.rank, r.old_rating, r.new_rating) on conflict do nothing;
    update public.profiles set rating = r.new_rating, max_rating = greatest(coalesce(max_rating, 0), r.new_rating)
     where id = r.user_id;
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$$;
revoke all on function public.apply_contest_ratings(integer, jsonb) from public, anon, authenticated;
grant execute on function public.apply_contest_ratings(integer, jsonb) to service_role;

