-- Activity for the heatmap: learning activity + problems solved, per day, last 370 days.
create or replace function public.get_activity(p_username text)
returns table (day date, count integer)
language sql stable security definer set search_path = public as $$
  with u as (
    select id from public.profiles p
    where p.username = p_username::citext
      and ((p.is_public and p.show_stats) or p.id = auth.uid() or public.is_staff(auth.uid()))
  ), learn as (
    select d.activity_date as day, greatest(1, d.lessons_completed + d.exercises_completed) as n
    from public.daily_activity d join u on u.id = d.user_id
    where d.xp_earned > 0 and d.activity_date >= (now() at time zone 'utc')::date - 370
  ), solved as (
    select (s.created_at at time zone 'utc')::date as day, count(distinct s.problem_id)::int as n
    from public.submissions s join u on u.id = s.user_id
    where s.verdict = 'OK' and s.created_at >= now() - interval '370 days'
    group by 1
  )
  select day, sum(n)::int from (select * from learn union all select * from solved) x group by day order by day;
$$;
grant execute on function public.get_activity(text) to anon, authenticated;

create or replace function public.get_solved_stats(p_username text)
returns table (all_time bigint, last_year bigint, last_month bigint)
language sql stable security definer set search_path = public as $$
