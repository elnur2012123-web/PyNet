-- =====================================================================
-- 0012: Cheat detector.
-- The server scans every finished round (and staff can scan any time):
--   * similar_code  two contestants' accepted code is (nearly) the same after
--                   removing comments and renaming variables
--   * fast_solve    a hard problem accepted suspiciously soon after the start
-- Flags wait in the Admin panel for a human decision (ban / disqualify / dismiss).
-- Ratings for a round wait until its flags are reviewed (or 48 hours pass).
-- =====================================================================

create table if not exists public.cheat_flags (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('similar_code','fast_solve')),
  severity text not null default 'medium' check (severity in ('low','medium','high')),
  contest_id integer references public.contests(id) on delete cascade,
  problem_id integer references public.problems(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  other_user_id uuid references auth.users(id) on delete cascade,
  submission_id bigint references public.submissions(id) on delete cascade,
  other_submission_id bigint references public.submissions(id) on delete cascade,
  score integer not null default 0,            -- similarity % or minutes
  details text not null default '',
  status text not null default 'open' check (status in ('open','dismissed','actioned')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists cheat_flags_unique on public.cheat_flags (kind, submission_id, coalesce(other_submission_id, 0));
create index if not exists cheat_flags_open on public.cheat_flags (status, created_at desc);

create table if not exists public.contest_disqualifications (
  contest_id integer not null references public.contests(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  reason text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (contest_id, user_id)
);

alter table public.contests add column if not exists checked_at timestamptz;

-- Staff only, through the server (service role). No browser access at all.
alter table public.cheat_flags enable row level security;
alter table public.contest_disqualifications enable row level security;
revoke all on public.cheat_flags, public.contest_disqualifications from anon, authenticated;

-- Standings (and therefore ratings) leave out disqualified contestants.
create or replace function public.get_contest_standings(p_contest integer)
returns table (rank bigint, user_id uuid, username text, rating integer, country text,
               solved integer, penalty integer, cells jsonb)
language sql stable security definer set search_path = public as $$
  with c as (
    select id, starts_at, starts_at + make_interval(mins => duration_minutes) as ends_at
    from public.contests where id = p_contest and starts_at <= now()
  ), subs as (
    select s.user_id, cp.letter, s.verdict, s.created_at
    from public.submissions s
    join c on s.contest_id = c.id and s.created_at < c.ends_at
    join public.contest_problems cp on cp.contest_id = c.id and cp.problem_id = s.problem_id
    where s.verdict <> 'CE' and not public.is_banned(s.user_id)
      and not exists (select 1 from public.contest_disqualifications d where d.contest_id = c.id and d.user_id = s.user_id)
  ), first_ok as (
    select user_id, letter, min(created_at) as ok_at from subs where verdict = 'OK' group by 1, 2
  ), per as (
    select s.user_id, s.letter,
      fo.ok_at is not null as ok,
      count(*) filter (where s.verdict <> 'OK' and (fo.ok_at is null or s.created_at < fo.ok_at))::int as wrong,
      case when fo.ok_at is not null then floor(extract(epoch from fo.ok_at - (select starts_at from c)) / 60)::int end as minute
    from subs s left join first_ok fo on fo.user_id = s.user_id and fo.letter = s.letter
    group by s.user_id, s.letter, fo.ok_at
  ), agg as (
    select user_id,
      count(*) filter (where ok)::int as solved,
      coalesce(sum(minute + 20 * wrong) filter (where ok), 0)::int as penalty,
      jsonb_object_agg(letter, jsonb_build_object('ok', ok, 'wrong', wrong, 'minute', minute)) as cells
    from per group by user_id
  )
  select rank() over (order by a.solved desc, a.penalty asc), a.user_id, p.username::text, p.rating, p.country,
         a.solved, a.penalty, a.cells
  from agg a join public.profiles p on p.id = a.user_id
  order by 1, p.username;
$$;
grant execute on function public.get_contest_standings(integer) to anon, authenticated;
